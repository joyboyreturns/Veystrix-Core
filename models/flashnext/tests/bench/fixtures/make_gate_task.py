"""Write the precomputed task text and its size record for a real-model gate (needs the real tokenizer; run it BEFORE the gate).

    .venv/bin/python -m models.flashnext.tests.bench.fixtures.make_gate_task --first-request 8200 --out gate_8k_task

The gate orchestrator must stay small (its memory counts as other anonymous memory in admission), so it never loads a
tokenizer: it reads these two files. The first request is the task text plus the harness's own framing
(``HARNESS_OVERHEAD``, measured by ``dsh_wire_probe`` with the trimmed glob+grep profile).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from models.flashnext.tests.bench.fixtures import agentic_fixture as F

HERE = Path(__file__).resolve().parent
CHECKPOINT = "~/models/Qwen3.8-Flash-Next-MLX-4bit-MTP"
HARNESS_OVERHEAD = 828


def task_text(sections: int, task: str) -> str:
    return F.brief(sections) + "\n\n## Task\n" + task


def build(tokenizer, first_request: int, task: str, overhead: int = HARNESS_OVERHEAD) -> dict:
    goal = first_request - overhead
    count = lambda n: len(tokenizer.encode(task_text(n, task), add_special_tokens=False))
    low, high = 1, 1
    while count(high) < goal:
        low, high = high, high * 2
    while low < high:
        mid = (low + high) // 2
        low, high = (mid + 1, high) if count(mid) < goal else (low, mid)
    text = task_text(low, task)
    return {"text": text, "meta": {"target_first_request": first_request, "harness_overhead_tokens": overhead,
                                   "task_text_tokens": count(low), "lines": low,
                                   "expected_first_request": count(low) + overhead, "task": task,
                                   "note": "generated by make_gate_task with the Qwen3.8-Flash-Next tokenizer"}}


if __name__ == "__main__":
    import os
    from transformers import AutoTokenizer

    ap = argparse.ArgumentParser()
    ap.add_argument("--first-request", type=int, required=True)
    ap.add_argument("--out", required=True, help="file stem inside fixtures/")
    ap.add_argument("--guided", action="store_true", help="state the glob -> grep order in the task")
    a = ap.parse_args()
    tok = AutoTokenizer.from_pretrained(os.path.expanduser(CHECKPOINT))
    built = build(tok, a.first_request, F.TASK_GUIDED if a.guided else F.TASK)
    (HERE / f"{a.out}.txt").write_text(built["text"])
    (HERE / f"{a.out}.json").write_text(json.dumps(built["meta"], indent=2))
    print(json.dumps(built["meta"], indent=2))
